"""Writes DEPENDENCIES.md: every crate the shipped app links on its three targets, with its
version, license and source repository, from `cargo tree`. Run it from the project root after
a dependency changes. The App Fair reviews the whole tree for DFSG-compliant licenses."""
import subprocess, collections

TARGETS = [("material", "aarch64-linux-android", "Android"),
           ("uikit", "aarch64-apple-ios", "iOS"),
           ("dom", "wasm32-unknown-unknown", "web")]

crates = collections.OrderedDict()
for feature, triple, name in TARGETS:
    out = subprocess.run(
        ["cargo", "tree", "-q", "--no-default-features", "--features", feature,
         "--target", triple, "-e", "normal", "--prefix", "none",
         "--format", "{p}|{l}|{r}"],
        check=True, capture_output=True, text=True).stdout
    for line in out.splitlines():
        line = line.replace(" (*)", "").replace(" (proc-macro)", "")
        pkg, lic, repo = (line.split("|") + ["", ""])[:3]
        if pkg.startswith("islewright "):
            continue
        entry = crates.setdefault(pkg, {"license": lic, "repo": repo, "targets": []})
        if name not in entry["targets"]:
            entry["targets"].append(name)

licenses = collections.Counter(c["license"] for c in crates.values())
with open("DEPENDENCIES.md", "w") as fh:
    fh.write("# Dependencies\n\n")
    fh.write("Every crate the app links, on Android, iOS and the web, with its license as the crate "
             "declares it. Generated by `tools/dependency_licenses.py`; do not edit by hand.\n\n")
    fh.write("All of them are free software under licenses that meet the Debian Free Software "
             "Guidelines and are compatible with Islewright's GNU GPL v3 or later. `self_cell` is "
             "used under Apache-2.0, one of its two licenses.\n\n")
    fh.write("| License | Crates |\n|---|---|\n")
    for lic, n in licenses.most_common():
        fh.write(f"| {lic} | {n} |\n")
    fh.write("\n| Crate | License | Targets | Source |\n|---|---|---|---|\n")
    for pkg in sorted(crates, key=str.lower):
        c = crates[pkg]
        fh.write(f"| {pkg} | {c['license']} | {', '.join(c['targets'])} | {c['repo']} |\n")
print(len(crates), "crates")
